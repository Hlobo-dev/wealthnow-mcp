"""Build the operation index both SDKs ship, from the live public OpenAPI spec.

Usage: python sdks/gen_operations.py [spec_url_or_path]
Writes sdks/python/src/wealthnow/_operations.json and sdks/typescript/src/operations.ts.
"""
import json
import pathlib
import sys
import urllib.request

SPEC = sys.argv[1] if len(sys.argv) > 1 else "https://firm.wealthnow.io/api/openapi.json"
here = pathlib.Path(__file__).resolve().parent

if SPEC.startswith("http"):
    with urllib.request.urlopen(SPEC, timeout=60) as r:
        spec = json.load(r)
else:
    spec = json.loads(pathlib.Path(SPEC).read_text())

ops = {}
for path, methods in spec["paths"].items():
    for method, op in methods.items():
        if method not in ("get", "post", "put", "patch", "delete"):
            continue
        params = op.get("parameters", [])
        ops[op["operationId"]] = {
            "method": method.upper(),
            "path": path,
            "path_params": [p["name"] for p in params if p.get("in") == "path"],
            "query_params": [p["name"] for p in params if p.get("in") == "query"],
            "body": bool(op.get("requestBody")),
            "min_plan": op.get("x-wealthnow-min-plan"),
            "summary": (op.get("summary") or "").strip(),
        }

# SDK names drop a legacy server-side prefix where the plain name is free.
for legacy in [k for k in ops if k.startswith("tengu_")]:
    plain = legacy[len("tengu_"):]
    if plain not in ops:
        ops[plain] = ops.pop(legacy)

meta = {"spec_version": spec["info"]["version"], "operations": dict(sorted(ops.items()))}
(here / "python/src/wealthnow/_operations.json").write_text(json.dumps(meta, indent=0, sort_keys=True) + "\n")
ts = ("// Generated by sdks/gen_operations.py from the public OpenAPI spec. Do not edit.\n"
      "import type { OperationIndex } from \"./types.js\";\n\n"
      f"export const SPEC_VERSION = {json.dumps(meta['spec_version'])};\n\n"
      f"export const OPERATIONS: OperationIndex = {json.dumps(meta['operations'], indent=2, sort_keys=True)};\n")
(here / "typescript/src/operations.ts").write_text(ts)
print(f"{len(ops)} operations from spec {meta['spec_version']}")
